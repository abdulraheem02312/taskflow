-- Database schema for Supabase Postgres. Runs on every server start, so
-- everything here must be safe to run again (IF NOT EXISTS / OR REPLACE).
--
-- Dates and times are stored as text in the same formats the app always used,
-- so the browser code doesn't change:
--   created_at style columns: 'YYYY-MM-DD HH:MM:SS' in UTC
--   due_date / start_date:    'YYYY-MM-DD'
--   completed_at:             ISO string from JavaScript
-- Flags (completed, archived, ...) are 0/1 integers, as before.

CREATE EXTENSION IF NOT EXISTS citext; -- case-insensitive text (tag names, invite emails)

-- Current UTC time as 'YYYY-MM-DD HH:MM:SS'
CREATE OR REPLACE FUNCTION now_text() RETURNS text LANGUAGE sql STABLE AS
  $$ SELECT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS') $$;

-- Today's date in a time zone (the server passes its own, e.g. 'Asia/Karachi')
CREATE OR REPLACE FUNCTION local_today(zone text) RETURNS text LANGUAGE sql STABLE AS
  $$ SELECT to_char(now() AT TIME ZONE zone, 'YYYY-MM-DD') $$;

CREATE TABLE IF NOT EXISTS users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  email text NOT NULL UNIQUE,
  password_hash text NOT NULL,
  created_at text NOT NULL DEFAULT now_text(),
  google_id text UNIQUE,
  home_layout text,
  notepad text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS sessions (
  token text PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at bigint NOT NULL
);

CREATE TABLE IF NOT EXISTS projects (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name text NOT NULL,
  color text NOT NULL DEFAULT '#f06a6a',
  created_at text NOT NULL DEFAULT now_text(),
  status text,
  due_date text,
  archived integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS sections (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id integer NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name text NOT NULL,
  position integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS tasks (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id integer NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  title text NOT NULL,
  notes text NOT NULL DEFAULT '',
  due_date text,
  completed integer NOT NULL DEFAULT 0,
  created_at text NOT NULL DEFAULT now_text(),
  section_id integer REFERENCES sections(id) ON DELETE SET NULL,
  position integer NOT NULL DEFAULT 0,
  priority text,                -- NULL, 'low', 'medium' or 'high'
  completed_at text,
  start_date text,              -- NULL means a one-day task
  assignee_id integer REFERENCES users(id) ON DELETE SET NULL,
  assigned_by integer REFERENCES users(id) ON DELETE SET NULL,
  repeat text                   -- 'daily', 'weekly', 'monthly' or NULL
);
CREATE INDEX IF NOT EXISTS tasks_project ON tasks (project_id);
CREATE INDEX IF NOT EXISTS tasks_section ON tasks (section_id);

CREATE TABLE IF NOT EXISTS subtasks (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id integer NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  title text NOT NULL,
  completed integer NOT NULL DEFAULT 0,
  position integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS subtasks_task ON subtasks (task_id);

-- Tags belong to a user and can be put on any of their tasks
CREATE TABLE IF NOT EXISTS tags (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name citext NOT NULL,
  color text NOT NULL,
  UNIQUE (user_id, name)
);

CREATE TABLE IF NOT EXISTS task_tags (
  task_id integer NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  tag_id integer NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
  PRIMARY KEY (task_id, tag_id)
);

-- ---------- Teams ----------

-- Who can open a project. The creator is the 'owner', everyone else a 'member'.
CREATE TABLE IF NOT EXISTS project_members (
  project_id integer NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role text NOT NULL DEFAULT 'member',
  created_at text NOT NULL DEFAULT now_text(),
  favorite integer NOT NULL DEFAULT 0, -- per person
  PRIMARY KEY (project_id, user_id)
);
CREATE INDEX IF NOT EXISTS project_members_user ON project_members (user_id);

-- Invites for emails that don't have an account yet; used up when they sign up
CREATE TABLE IF NOT EXISTS project_invites (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id integer NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  email citext NOT NULL,
  invited_by integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at text NOT NULL DEFAULT now_text(),
  UNIQUE (project_id, email)
);

CREATE TABLE IF NOT EXISTS comments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id integer NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  body text NOT NULL,
  created_at text NOT NULL DEFAULT now_text()
);
CREATE INDEX IF NOT EXISTS comments_task ON comments (task_id);

-- Inbox: one row per notification for one person
CREATE TABLE IF NOT EXISTS notifications (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  actor_id integer REFERENCES users(id) ON DELETE SET NULL,
  type text NOT NULL,
  project_id integer REFERENCES projects(id) ON DELETE CASCADE,
  task_id integer REFERENCES tasks(id) ON DELETE CASCADE,
  body text,
  read_at text,
  created_at text NOT NULL DEFAULT now_text(),
  archived_at text,
  bookmarked integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS notifications_user ON notifications (user_id, id);

-- "Forgot password" links. Only a hash of the token is stored, so a leaked
-- database can't be used to reset anyone's password.
CREATE TABLE IF NOT EXISTS password_resets (
  token_hash text PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at bigint NOT NULL,
  created_at bigint NOT NULL
);

-- Files attached to tasks. The file itself lives in Supabase Storage under a random
-- stored_name; the original name is only used when showing or downloading it.
-- If the uploader deletes their account, the file stays with the team's task.
CREATE TABLE IF NOT EXISTS attachments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id integer NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  name text NOT NULL,
  size bigint NOT NULL,
  stored_name text NOT NULL UNIQUE,
  created_at text NOT NULL DEFAULT now_text()
);
CREATE INDEX IF NOT EXISTS attachments_task ON attachments (task_id);

-- ---------- Status, portfolios, goals, rules, forms ----------

-- "On track / At risk / ..." updates posted on a project
CREATE TABLE IF NOT EXISTS status_updates (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id integer NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  user_id integer REFERENCES users(id) ON DELETE SET NULL,
  status text NOT NULL,
  body text NOT NULL DEFAULT '',
  created_at text NOT NULL DEFAULT now_text()
);

-- A portfolio is a personal folder of projects to watch together
CREATE TABLE IF NOT EXISTS portfolios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name text NOT NULL,
  color text NOT NULL DEFAULT '#60a5fa',
  created_at text NOT NULL DEFAULT now_text()
);
CREATE TABLE IF NOT EXISTS portfolio_projects (
  portfolio_id integer NOT NULL REFERENCES portfolios(id) ON DELETE CASCADE,
  project_id integer NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  PRIMARY KEY (portfolio_id, project_id)
);

-- Goals: progress typed in by hand, or measured from linked projects
CREATE TABLE IF NOT EXISTS goals (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title text NOT NULL,
  notes text NOT NULL DEFAULT '',
  due_date text,
  status text,
  progress integer NOT NULL DEFAULT 0,
  created_at text NOT NULL DEFAULT now_text()
);
CREATE TABLE IF NOT EXISTS goal_projects (
  goal_id integer NOT NULL REFERENCES goals(id) ON DELETE CASCADE,
  project_id integer NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  PRIMARY KEY (goal_id, project_id)
);

-- Rules: "when <trigger> then <action>" inside one project
CREATE TABLE IF NOT EXISTS rules (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id integer NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  trigger text NOT NULL,
  trigger_value integer,
  action text NOT NULL,
  action_value text,
  enabled integer NOT NULL DEFAULT 1,
  created_by integer REFERENCES users(id) ON DELETE SET NULL,
  created_at text NOT NULL DEFAULT now_text()
);

-- A public form that turns submissions into tasks (one per project)
CREATE TABLE IF NOT EXISTS forms (
  project_id integer PRIMARY KEY REFERENCES projects(id) ON DELETE CASCADE,
  token text NOT NULL UNIQUE,
  enabled integer NOT NULL DEFAULT 0,
  title text NOT NULL DEFAULT '',
  description text NOT NULL DEFAULT '',
  section_id integer
);

-- ---------- Dependencies, likes, My Tasks state ----------

-- task_id can't really start until blocked_by_id is done
CREATE TABLE IF NOT EXISTS task_dependencies (
  task_id integer NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  blocked_by_id integer NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  PRIMARY KEY (task_id, blocked_by_id)
);

-- Likes on tasks and comments (kind = 'task' or 'comment')
CREATE TABLE IF NOT EXISTS likes (
  kind text NOT NULL,
  item_id integer NOT NULL,
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (kind, item_id, user_id)
);

CREATE OR REPLACE FUNCTION likes_task_gone() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  DELETE FROM likes WHERE kind = 'task' AND item_id = old.id;
  RETURN old;
END $$;
CREATE OR REPLACE FUNCTION likes_comment_gone() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  DELETE FROM likes WHERE kind = 'comment' AND item_id = old.id;
  RETURN old;
END $$;
CREATE OR REPLACE TRIGGER likes_task_gone AFTER DELETE ON tasks FOR EACH ROW EXECUTE FUNCTION likes_task_gone();
CREATE OR REPLACE TRIGGER likes_comment_gone AFTER DELETE ON comments FOR EACH ROW EXECUTE FUNCTION likes_comment_gone();

-- My Tasks: "Doing" is personal (To do is the default, Done is the task being completed)
CREATE TABLE IF NOT EXISTS my_task_state (
  user_id integer NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  task_id integer NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  state text NOT NULL,
  PRIMARY KEY (user_id, task_id)
);

-- Only this server talks to the database (with its own connection), never the
-- browser. Row Level Security with no policies keeps Supabase's public API
-- from reading or changing any of these tables.
DO $$
DECLARE t text;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;
